export async function seedInitialData(database: AppDatabase = db): Promise<{
  propertiesCount: number;
  customersCount: number;
  linksCount: number;
}> {
  await database.transaction("rw", [database.properties, database.customers, database.customer_property_links], async () => {
    await database.properties.bulkPut(SEED_PROPERTIES);
    await database.customers.bulkPut(SEED_CUSTOMERS);
    await database.customer_property_links.bulkPut(SEED_LINKS);
  });

  return {
    propertiesCount: SEED_PROPERTIES.length,
    customersCount: SEED_CUSTOMERS.length,
    linksCount: SEED_LINKS.length
  };
}

